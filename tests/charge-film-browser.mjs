import{chromium}from'playwright';
import assert from'node:assert/strict';
import {mkdir} from'node:fs/promises';
await mkdir('.tmp',{recursive:true});
const browser=await chromium.launch({executablePath:process.env.CHROME_PATH||'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',headless:true,args:['--use-angle=swiftshader','--enable-unsafe-swiftshader']});
try{
 const page=await browser.newPage({viewport:{width:1440,height:1000},reducedMotion:'no-preference'}),errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 await page.goto((process.env.TEST_URL||'http://127.0.0.1:3000/')+'#charge');
 await page.waitForFunction(()=>document.querySelector('#scene').dataset.state==='ready',{},{timeout:45000});
 await page.click('[data-language="en"]');
 await page.evaluate(()=>{
  window.chargeStages=[];
  const scene=document.querySelector('#scene');
  new MutationObserver(()=>{const stage=scene.dataset.connection;if(stage&&window.chargeStages.at(-1)!==stage)window.chargeStages.push(stage);}).observe(scene,{attributes:true,attributeFilter:['data-connection']});
 });
 await page.click('[data-action="open"]');await page.click('[data-action="plug"]');
 assert.equal(await page.locator('[data-action="stop"]').isDisabled(),true);
 await page.screenshot({path:'.tmp/charge-film-wide.png'});
 await page.waitForFunction(()=>document.querySelector('#scene').dataset.connection==='insert',{},{timeout:60000});
 await page.screenshot({path:'.tmp/charge-film-insert.png'});
 await page.waitForFunction(()=>document.querySelector('#scene').dataset.connection==='hold',{},{timeout:60000});
 assert.equal(await page.locator('.identity').evaluate(el=>getComputedStyle(el).opacity),'0');
 await page.screenshot({path:'.tmp/charge-film-seated.png'});
 await page.waitForFunction(()=>!document.querySelector('#scene').dataset.connection,{},{timeout:60000});
 await page.screenshot({path:'.tmp/charge-film-end.png'});
 assert.deepEqual(await page.evaluate(()=>window.chargeStages),['wide','approach','insert','hold','return']);
 assert.equal(await page.locator('[data-action="stop"]').isEnabled(),true);
 await page.click('[data-connection="replay"]');await page.click('[data-connection="skip"]');
 assert.equal(await page.locator('#scene').getAttribute('data-connection'),'');
 await page.click('[data-connection="replay"]');await page.click('[data-chapter="frunk"]');
 assert.equal(await page.locator('#scene').getAttribute('data-connection'),'');
 assert.equal(await page.locator('#scene').getAttribute('data-operation'),'frunk');
 await page.click('[data-chapter="charge"]');await page.click('[data-language="de"]');
 await page.emulateMedia({reducedMotion:'reduce'});
 await page.click('[data-connection="replay"]');
 assert.equal(await page.locator('#scene').getAttribute('data-connection'),'');
 assert.equal(await page.locator('#scene').getAttribute('data-shot'),'chargeClose');
 await page.setViewportSize({width:375,height:812});
 await page.emulateMedia({reducedMotion:'no-preference'});
 await page.click('[data-connection="replay"]');
 await page.waitForFunction(()=>document.querySelector('#scene').dataset.connection==='hold',{},{timeout:60000});
 assert.ok(await page.locator('#scene').evaluate(el=>{const r=el.getBoundingClientRect();return r.top>=0&&r.bottom<=innerHeight;}),'mobile replay must bring the 3D scene into view');
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'mobile horizontal overflow');
 await page.screenshot({path:'.tmp/charge-film-mobile.png'});
 await page.waitForFunction(()=>!document.querySelector('#scene').dataset.connection,{},{timeout:60000});
 await page.click('[data-connection="replay"]');
 await page.emulateMedia({reducedMotion:'reduce'});
 await page.waitForFunction(()=>!document.querySelector('#scene').dataset.connection);
 assert.equal(await page.locator('[data-action="stop"]').isEnabled(),true);
 assert.equal(await page.locator('[data-connection="replay"]').textContent(),'Verbindung im Detail ansehen');
 await page.setViewportSize({width:1440,height:1000});
 await page.click('[data-connection="replay"]');
 for(const action of ['stop','unlock','unplug','close'])await page.click('[data-action="'+action+'"]');
 assert.equal(await page.locator('#scene').getAttribute('data-operation-phase'),'closed');
 await page.screenshot({path:'.tmp/charge-closed-close.png'});
 await page.click('[data-view="rear"]');
 await page.locator('#scene').screenshot({path:'.tmp/charge-closed-left.png'});
 for(let i=0;i<4;i++)await page.click('#orbitRight');
 await page.locator('#scene').screenshot({path:'.tmp/charge-closed-right.png'});
 await page.click('[data-chapter="frunk"]');
 await page.click('[data-action="release"]');await page.click('[data-action="lift"]');
 await page.locator('#scene').screenshot({path:'.tmp/charge-closed-frunk.png'});
 assert.deepEqual(errors,[]);
 console.log('PASS: full five-stage charging film, replay, skip, chapter cancellation, DE/EN controls, mobile framing, reduced-motion inspection/cancellation, closed left/right corner views, and independent frunk opening.');
}finally{await browser.close();}
